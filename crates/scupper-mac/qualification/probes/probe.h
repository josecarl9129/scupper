static bool qual_first = true;
static inline uint64_t nanoseconds(void) {
  struct timespec t = {0};
  if (clock_gettime(CLOCK_MONOTONIC, &t))
    _exit(2);
  return (uint64_t)t.tv_sec * UINT64_C(1000000000) + (uint64_t)t.tv_nsec;
}
static inline uint64_t millis(void) { return nanoseconds() / 1000000; }
static inline void pause_ms(unsigned n) {
  struct timespec t = {.tv_sec = n / 1000,
                       .tv_nsec = (long)(n % 1000) * 1000000};
  while (nanosleep(&t, &t) && errno == EINTR) {
  }
}
static inline void string(const char *s) {
  putchar('"');
  /* Drop entire sensitive lines before escaping, including diagnostic prefixes.
   */
  while (*s) {
    const char *end = strchr(s, '\n');
    size_t n = end ? (size_t)(end - s) : strlen(s);
    char *line = strndup(s, n);
    if (!line)
      _exit(2);
    if (strcasestr(line, "private_key=") ||
        strcasestr(line, "preshared_key=")) {
      fputs("[redacted key material]", stdout);
    } else
      for (size_t i = 0; i < n; ++i) {
        unsigned char c = (unsigned char)line[i];
        if (c == '"' || c == '\\')
          printf("\\%c", c);
        else if (c < 32 || c >= 127)
          printf("\\u%04x", c);
        else
          putchar(c);
      }
    free(line);
    if (!end)
      break;
    fputs("\\n", stdout);
    s = end + 1;
  }
  putchar('"');
}
static inline void event(const char *name) {
  if (!qual_first)
    putchar(',');
  qual_first = false;
  fputs("{\"event\":", stdout);
  string(name);
}
static inline void question(const char *id, int holds, unsigned iterations) {
  event("question");
  fputs(",\"question\":", stdout);
  string(id);
  fputs(",\"verdict\":", stdout);
  string(holds < 0 ? "inconclusive"
         : holds   ? "assumption_holds"
                   : "assumption_refuted");
  printf(",\"iterations\":%u}", iterations);
}
static inline void journal(const char *line) {
  char path[PATH_MAX];
  if (snprintf(path, sizeof(path), "%s/resources.jsonl", qual_out) >=
      (int)sizeof(path))
    _exit(2);
  int fd = open(path, O_WRONLY | O_APPEND | O_CREAT | O_CLOEXEC, 0600);
  size_t n = strlen(line);
  if (fd < 0 || write(fd, line, n) != (ssize_t)n || fsync(fd))
    _exit(2);
  close(fd);
}
static inline void journal_child(pid_t pid, const char *kind) {
  struct proc_bsdinfo p = {0};
  if (proc_pidinfo(pid, PROC_PIDTBSDINFO, 0, &p, sizeof(p)) != (int)sizeof(p))
    _exit(2);
  char line[512];
  snprintf(line, sizeof(line),
           "{\"kind\":\"%s\",\"pid\":%d,\"start\":\"%" PRIu64 ":%" PRIu64
           "\",\"at\":%lld}\n",
           kind, pid, (uint64_t)p.pbi_start_tvsec, (uint64_t)p.pbi_start_tvusec,
           (long long)time(NULL));
  journal(line);
}
static inline void resource(const char *kind, const char *path) {
  /* All resource paths are generated by the harness, never arbitrary input. */
  if (strchr(path, '"') || strchr(path, '\\') || strchr(path, '\n'))
    _exit(2);
  char line[PATH_MAX + 128];
  snprintf(line, sizeof(line), "{\"kind\":\"%s\",\"path\":\"%s\"}\n", kind,
           path);
  journal(line);
}
static inline void begin(int argc, char **argv) {
  if (argc < 2 || argv[1][0] != '/')
    _exit(2);
  const char *gha = getenv("GITHUB_ACTIONS"),
             *runner = getenv("RUNNER_ENVIRONMENT");
  if (geteuid() != 0 || !gha || strcmp(gha, "true") || !runner ||
      strcmp(runner, "github-hosted"))
    _exit(2);
  qual_out = argv[1];
  qual_self = argv[0];
  alarm(85);
  journal_child(getpid(), argc == 3 && !strcmp(argv[2], "--inventory")
                              ? "inventory"
                              : "probe");
  setbuf(stdout, NULL);
  fputs("{\"events\":[", stdout);
}
static inline int end(void) {
  fputs("]}\n", stdout);
  return ferror(stdout) ? 1 : 0;
}

struct output {
  int status;
  bool timeout;
  char out[65536];
  char err[65536];
  pid_t pid;
};
static inline void drain(int fd, char *dst, size_t *used) {
  char buf[4096];
  ssize_t n;
  while ((n = read(fd, buf, sizeof(buf))) > 0) {
    if (*used + (size_t)n >= 65536)
      _exit(2); /* no silent truncation */
    memcpy(dst + *used, buf, (size_t)n);
    *used += (size_t)n;
    dst[*used] = 0;
  }
}
static inline struct output run_for(char *const args[], const char *kind,
                                    unsigned budget_ms) {
  struct output o = {.status = -1};
  int a[2], b[2], gate[2];
  if (pipe(a) || pipe(b) || pipe(gate))
    _exit(2);
  pid_t pid = fork();
  if (pid < 0)
    _exit(2);
  if (!pid) {
    close(a[0]);
    close(b[0]);
    close(gate[1]);
    char go;
    if (read(gate[0], &go, 1) != 1)
      _exit(2);
    close(gate[0]);
    if (dup2(a[1], 1) < 0 || dup2(b[1], 2) < 0)
      _exit(2);
    close(a[1]);
    close(b[1]);
    execv(args[0], args);
    _exit(127);
  }
  close(a[1]);
  close(b[1]);
  close(gate[0]);
  journal_child(pid,
                kind); /* durable before exec, especially before pfctl -E */
  if (write(gate[1], "x", 1) != 1)
    _exit(2);
  close(gate[1]);
  o.pid = pid;
  if (fcntl(a[0], F_SETFL, O_NONBLOCK) || fcntl(b[0], F_SETFL, O_NONBLOCK))
    _exit(2);
  uint64_t deadline = millis() + budget_ms;
  size_t na = 0, nb = 0;
  int status = 0;
  for (;;) {
    drain(a[0], o.out, &na);
    drain(b[0], o.err, &nb);
    pid_t w = waitpid(pid, &status, WNOHANG);
    if (w == pid)
      break;
    if (w < 0)
      _exit(2);
    if (millis() >= deadline) {
      o.timeout = true;
      kill(pid, SIGKILL);
      break;
    }
    pause_ms(5);
  }
  if (o.timeout) {
    uint64_t reap = millis() + 1000;
    while (waitpid(pid, &status, WNOHANG) == 0 && millis() < reap)
      pause_ms(5);
  }
  drain(a[0], o.out, &na);
  drain(b[0], o.err, &nb);
  close(a[0]);
  close(b[0]);
  if (!o.timeout && WIFEXITED(status))
    o.status = WEXITSTATUS(status);
  event("command");
  fputs(",\"argv\":[", stdout);
  for (int i = 0; args[i]; ++i) {
    if (i)
      putchar(',');
    string(args[i]);
  }
  printf("],\"pid\":%d,\"exit_code\":%d,\"timed_out\":%s,\"stdout\":", pid,
         o.status, o.timeout ? "true" : "false");
  string(o.out);
  fputs(",\"stderr\":", stdout);
  string(o.err);
  putchar('}');
  return o;
}
static inline struct output run(char *const args[], const char *kind) {
  return run_for(args, kind, 8000);
}
#define RUN_FOR(ms, ...)                                                       \
  run_for((char *const[]){__VA_ARGS__, NULL}, "child", ms)
#define RUN(...) run((char *const[]){__VA_ARGS__, NULL}, "child")
static inline struct output pf(const char *arg) {
  return RUN("/sbin/pfctl", (char *)arg);
}
static inline struct output refs(void) {
  return RUN("/sbin/pfctl", "-s", "References");
}
static inline int enabled(void) {
  struct output o = RUN("/sbin/pfctl", "-s", "info");
  if (o.status || o.timeout)
    return -1;
  if (strstr(o.out, "Status: Enabled"))
    return 1;
  if (strstr(o.out, "Status: Disabled"))
    return 0;
  return -1;
}
static inline uint64_t acquire(void) {
  struct output o =
      run((char *const[]){"/sbin/pfctl", "-E", NULL}, "pf-acquire");
  const char *p = strstr(o.err, "Token : ");
  if (!p)
    p = strstr(o.out, "Token : ");
  if (o.status || o.timeout || !p)
    _exit(2);
  char *tail;
  errno = 0;
  uint64_t token = strtoull(p + 8, &tail, 10);
  if (errno || tail == p + 8 || !token)
    _exit(2);
  char line[128];
  snprintf(line, sizeof(line), "{\"kind\":\"token\",\"token\":%" PRIu64 "}\n",
           token);
  journal(line);
  return token;
}
static inline bool release(uint64_t t) {
  char token[32];
  snprintf(token, sizeof(token), "%" PRIu64, t);
  struct output o = RUN("/sbin/pfctl", "-X", token);
  return o.status == 0 && !o.timeout;
}
