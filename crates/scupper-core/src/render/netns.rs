//! M2 kill switch: only client-to-exit and directional return forwarding.

use std::collections::BTreeSet;

use crate::config::{GatewayId, ValidatedSite};

use super::{RenderError, VersionStamp};

/// Renders the M2 subset of DESIGN §5.2 inside the owned namespace.
///
/// All interface matches except loopback use names, so tunnels need not exist
/// when the ruleset is checked or loaded. M2 validation forbids IPv6 addresses:
/// the empty v6 sets drop all client v6 at antispoof and permit no v6 forwarding.
/// No uplink identity or endpoint is used. Topology lemma T supplies the
/// post-NAT uplink barrier, including for locally generated related ICMP errors.
///
/// # Errors
/// Returns [`RenderError::UnknownGateway`] if the requested gateway is absent.
pub fn render_netns(
    site: &ValidatedSite,
    gateway: &GatewayId,
    stamp: &VersionStamp,
) -> Result<String, RenderError> {
    const HEX: &[u8] = b"0123456789abcdef";
    let gw = site.gateway(gateway).ok_or(RenderError::UnknownGateway)?;
    let sha256: String = stamp
        .sha256
        .iter()
        .flat_map(|byte| {
            [
                char::from(HEX[usize::from(byte >> 4)]),
                char::from(HEX[usize::from(byte & 15)]),
            ]
        })
        .collect();
    let mut output = format!(
        concat!(
            "#!/usr/sbin/nft -f\n",
            "# Generated by scupper from config version {} (sha256 {}). Do not edit.\n",
            "# Loaded inside network namespace \"scupper\", which contains no uplink: no\n",
            "# packet can leave it except through a WireGuard tunnel. This ruleset decides\n",
            "# which tunnel and keeps clients isolated.\n",
            "flush ruleset\n\n",
            "table inet scupper {{\n",
        ),
        stamp.version, sha256,
    );
    output.push_str(&set(
        "client_ifaces",
        "ifname",
        [format!("\"{}\"", gw.client_tunnel().ifname())],
    ));
    output.push_str(&set(
        "exit_ifaces",
        "ifname",
        gw.exits()
            .iter()
            .map(|exit| format!("\"{}\"", exit.ifname())),
    ));
    output.push_str(&set("exit_ifaces_v6", "ifname", []));
    output.push_str(&set(
        "client_nets4",
        "ipv4_addr; flags interval",
        site.devices()
            .values()
            .filter(|device| device.gateways().contains(gateway))
            .map(|device| device.address4().to_string()),
    ));
    output.push_str(&set("client_nets6", "ipv6_addr; flags interval", []));
    output.push('\n');
    output.push_str(CHAINS);
    Ok(output)
}

fn set(name: &str, kind: &str, elements: impl IntoIterator<Item = String>) -> String {
    let elements: BTreeSet<_> = elements.into_iter().collect();
    let mut text = format!("\tset {name} {{ type {kind};");
    if !elements.is_empty() {
        text.push_str(" elements = { ");
        text.push_str(&elements.into_iter().collect::<Vec<_>>().join(", "));
        text.push_str(" }");
    }
    text.push_str(" }\n");
    text
}

const CHAINS: &str = r#"	counter fwd_dropped { }

	# Second layer behind WireGuard's AllowedIPs check.
	chain antispoof {
		type filter hook prerouting priority raw; policy accept;
		iifname @client_ifaces ip saddr != @client_nets4 drop
		iifname @client_ifaces ip6 saddr != @client_nets6 drop
		# Exit peers have AllowedIPs 0.0.0.0/0: a provider-side packet must never
		# carry a client source address.
		iifname @exit_ifaces ip saddr @client_nets4 drop
		iifname @exit_ifaces ip6 saddr @client_nets6 drop
	}

	# I7: clients reach only rate-limited ping and ND in M2.
	# From exits only replies to the gateway's own traffic.
	chain input {
		type filter hook input priority filter; policy drop;
		iif "lo" accept
		ct state invalid drop
		ct state established,related accept
		iifname @client_ifaces icmp type echo-request limit rate 10/second accept
		iifname @client_ifaces icmpv6 type echo-request limit rate 10/second accept
		iifname @client_ifaces icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert } accept
	}

	chain forward {
		type filter hook forward priority filter; policy drop;
		# TCP of flows whose state was flushed (failover, restore) is invalid
		# (nf_conntrack_tcp_loose=0); reset it so client applications reconnect.
		iifname @client_ifaces meta l4proto tcp ct state invalid reject with tcp reset
		ct state invalid drop
		# Client to exit: any configured exit; the route picks the active one.
		iifname @client_ifaces meta nfproto ipv4 oifname @exit_ifaces accept
		iifname @client_ifaces meta nfproto ipv6 oifname @exit_ifaces_v6 accept
		# Return traffic: directional, established/related only (bug 2).
		iifname @exit_ifaces oifname @client_ifaces ct state established,related accept
		# Deny by omission: no client-to-client, no new flows from exits.
		counter name "fwd_dropped" drop
	}

	chain postrouting {
		type nat hook postrouting priority srcnat; policy accept;
		oifname @exit_ifaces masquerade
	}

	# Locally generated packets (kernel RSTs and ICMP errors, forwarder
	# upstream queries, probes) may only use the namespace's own tunnels
	# (bug 3). A foreign interface becomes a drop, not a path.
	chain output {
		type filter hook output priority filter; policy drop;
		oif "lo" accept
		oifname @client_ifaces accept
		oifname @exit_ifaces accept
	}
}
"#;
